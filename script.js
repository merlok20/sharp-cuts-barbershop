// ===== Language Switcher =====
function applyLanguage(lang) {
  currentLang = lang;
  const t = translations[lang];

  document.documentElement.lang = lang === 'uk' ? 'uk' : 'en';

  document.querySelectorAll('[data-key]').forEach(el => {
    const key = el.getAttribute('data-key');
    if (t[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'SELECT') {
        el.setAttribute('placeholder', t[key]);
      } else {
        el.textContent = t[key];
      }
    }
  });

  // Update gallery labels dynamically
  updateGalleryLabels(lang);

  // Update lang buttons
  langUk.classList.toggle('active', lang === 'uk');
  langEn.classList.toggle('active', lang === 'en');

  localStorage.setItem('sharpcuts_lang', lang);
}

function updateGalleryLabels(lang) {
  const t = translations[lang];
  document.querySelectorAll('.gallery-label').forEach((label, i) => {
    if (t.gallery_labels && t.gallery_labels[i]) {
      label.textContent = t.gallery_labels[i];
    }
  });
}

